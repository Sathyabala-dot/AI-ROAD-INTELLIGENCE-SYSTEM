"""
health_score_target.py

Creates the Road Health Score TARGET (y) used for training.

============================================================
IMPORTANT — WHY THIS FILE EXISTS (read this for your viva)
============================================================
The supplied dataset (real or the synthetic sample generated by
generate_sample_data.py) does NOT contain an official labelled
Road Health Score column. This is CASE B from the project brief:

    "The Road Health Score is a project-derived target created from
    available road-condition indicators because the supplied dataset
    does not contain an official labelled Road Health Score."

This is NOT an official Tamil Nadu government road-health standard.
It is a transparent, reproducible, weighted-penalty formula built only
from columns that genuinely exist in the dataset. If you later obtain
a dataset with a real labelled health score, DELETE this module and
use that column directly as `y` in training/train_health_model.py
(see the CASE A branch noted there).

============================================================
METHODOLOGY (fully reproducible, documented for the report)
============================================================
Start at 100 (perfect road) and subtract penalties:

    - pothole_count            -> up to 25 points
    - damage_count              -> up to 15 points
    - damaged_area_percent      -> up to 25 points (direct scaled)
    - damage_severity (0-5)     -> up to 15 points
    - low confidence_score      -> small penalty if detection is unreliable
    - days_since_maintenance    -> up to 15 points (long-neglected roads)
    - rainfall_mm (recent)      -> up to 5 points (wet-weather stress proxy)

All penalty components are capped and combined additively, then the
result is clipped to [0, 100]. Weights are documented constants below
so they can be tuned/justified in the report; they are NOT learned.
"""

from __future__ import annotations
import numpy as np
import pandas as pd

# Documented, tunable weights (sum of max penalties = 100)
WEIGHTS = {
    "pothole_count_max_penalty": 25,
    "pothole_count_saturation": 20,       # potholes at/above this -> full penalty
    "damage_count_max_penalty": 15,
    "damage_count_saturation": 15,
    "damaged_area_max_penalty": 25,       # scales directly with % (0-100)
    "damage_severity_max_penalty": 15,    # severity is already 0-5
    "confidence_penalty_max": 5,          # penalty when detector confidence is low
    "maintenance_neglect_max_penalty": 15,
    "maintenance_neglect_saturation_days": 730,
    "rainfall_max_penalty": 5,
    "rainfall_saturation_mm": 50,
}


def _scaled_penalty(value: pd.Series, saturation: float, max_penalty: float) -> pd.Series:
    value = value.fillna(0).clip(lower=0)
    return (value.clip(upper=saturation) / saturation) * max_penalty


def compute_health_score(df: pd.DataFrame) -> pd.Series:
    """Compute the derived Road Health Score (0-100) for each row.

    Only uses columns that are actually present in `df`; missing optional
    columns simply contribute zero penalty (documented assumption).
    """
    score = pd.Series(100.0, index=df.index)

    if "pothole_count" in df.columns:
        score -= _scaled_penalty(
            df["pothole_count"],
            WEIGHTS["pothole_count_saturation"],
            WEIGHTS["pothole_count_max_penalty"],
        )

    if "damage_count" in df.columns:
        score -= _scaled_penalty(
            df["damage_count"],
            WEIGHTS["damage_count_saturation"],
            WEIGHTS["damage_count_max_penalty"],
        )

    if "damaged_area_percent" in df.columns:
        pct = df["damaged_area_percent"].fillna(0).clip(0, 100)
        score -= (pct / 100.0) * WEIGHTS["damaged_area_max_penalty"]

    if "damage_severity" in df.columns:
        sev = df["damage_severity"].fillna(0).clip(0, 5)
        score -= (sev / 5.0) * WEIGHTS["damage_severity_max_penalty"]

    if "confidence_score" in df.columns:
        conf = df["confidence_score"].fillna(1.0).clip(0, 1)
        # low confidence adds a small uncertainty penalty
        score -= (1 - conf) * WEIGHTS["confidence_penalty_max"]

    if "days_since_maintenance" in df.columns:
        score -= _scaled_penalty(
            df["days_since_maintenance"],
            WEIGHTS["maintenance_neglect_saturation_days"],
            WEIGHTS["maintenance_neglect_max_penalty"],
        )

    if "rainfall_mm" in df.columns:
        score -= _scaled_penalty(
            df["rainfall_mm"],
            WEIGHTS["rainfall_saturation_mm"],
            WEIGHTS["rainfall_max_penalty"],
        )

    return score.clip(0, 100).round(2)


def classify_condition(score: float) -> str:
    """Project-defined classification thresholds (documented, not an
    external/authoritative standard)."""
    if score >= 80:
        return "Excellent"
    elif score >= 60:
        return "Good"
    elif score >= 40:
        return "Moderate"
    elif score >= 20:
        return "Poor"
    else:
        return "Critical"
